        if not commodity_str or str(commodity_str).strip() == "":
            return ""

        commodity_lower = str(commodity_str).lower()
        categories_found = set()

        for category, keywords in self.categories.items():
            for keyword in keywords:
                if keyword in commodity_lower:
                    categories_found.add(category)
                    break

        if not categories_found:
            return ""
        elif len(categories_found) == 1:
            return list(categories_found)[0]
        else:
            return ", ".join(sorted(categories_found))



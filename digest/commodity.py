    def normalize(self, commodity_str: str) -> str:
        """Нормалізує сировину, замінюючи синоніми на канонічні форми"""
        if not commodity_str or str(commodity_str).strip() == "":
            return ""

        commodity_lower = str(commodity_str).lower().strip()

        # Розділяємо на частини (через кому)
        parts = [p.strip() for p in commodity_lower.split(',')]

        # Нормалізуємо кожну частину
        normalized_parts = []
        for part in parts:
            if not part:
                continue

            # Шукаємо точне збіг або підстановку
            normalized = self.synonyms.get(part, None)

            # Якщо точного збігу немає, шукаємо часткове збіг
            if not normalized:
                for syn, canonical in self.synonyms.items():
                    if syn in part:
                        normalized = canonical
                        break

            # Якщо все ще не знайшлось, використовуємо оригінал
            if not normalized:
                normalized = part

            if normalized not in normalized_parts:  # Уникаємо дублів
                normalized_parts.append(normalized)

        return ", ".join(normalized_parts)


